/**
 * Instantiates a fresh WfpProject from a WfpProjectTemplate
 * Generates fresh unique IDs, timestamps, and deep copies tracks/clips
 */
export function instantiateTemplateProject(template: WfpProjectTemplate): WfpProject {
  const timestamp = Date.now();
  const slug = template.name.toLowerCase().replace(/[^a-z0-9]+/g, '_');

  // Deep clone tracks with fresh IDs
  const clonedTracks = template.tracks.map((t) => ({
    ...t,
    id: `track_${Math.random().toString(36).slice(2, 8)}`,
  }));

  // Deep clone clips with fresh IDs
  const clonedClips = template.clips.map((c) => ({
    ...c,
    id: `clip_${Math.random().toString(36).slice(2, 9)}`,
  }));

  return {
    format: 'WFP_JSON_V2',
    application: 'CineCraft Pro Studio',
    version: '16.0.0',
    id: `wfp_${timestamp}`,
    name: `${template.name} Starter`,
    filename: `${slug}_starter_${timestamp.toString().slice(-4)}.wfp`,
    aspectRatio: template.aspectRatio,
    resolution: {
      width: template.resolution.width,
      height: template.resolution.height,
      label: template.resolution.label,
    },
    fps: template.fps,
    duration: template.duration,
    createdAt: timestamp,
    lastEdited: timestamp,
    thumbnailGradient: template.thumbnailGradient,
    sizeMb: +(1.2 + Math.random() * 0.8).toFixed(1),
    tracks: clonedTracks,
    clips: clonedClips,
    tags: [...template.tags, 'Template', template.aspectRatio],
  };
}
